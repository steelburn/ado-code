/**
 * Digest-first headers for generated markdown artifacts (ADO-27354).
 *
 * Agents re-read generated docs whole with `read_file` on top of the copies
 * already injected into the prompt, so a 40 KB repo.md costs ~10K tokens per
 * read while a 10-line digest costs a few hundred. Every generated artifact
 * therefore opens with a short machine-written digest that answers the common
 * questions; the full detail follows below.
 *
 * The block is delimited by HTML comments so it can be stripped and rewritten
 * idempotently — a re-sync replaces the digest instead of stacking another.
 */

export const DIGEST_START = '<!-- ado-code:digest:start -->';
export const DIGEST_END = '<!-- ado-code:digest:end -->';

/** Hard ceiling for the digest block, markers and footer included. */
export const MAX_DIGEST_LINES = 15;

export interface DocDigestSpec {
  /** What the artifact is, e.g. "repository facts". */
  kind: string;
  /** Fact lines; each renders as one bullet, capped to fit the line budget. */
  facts: string[];
  /** Optional pointer sentence replacing the default footer. */
  footer?: string;
}

const DEFAULT_FOOTER =
  'Full detail follows below — read a line range with `read_file` instead of the whole file.';

/** Remove an existing digest block (and the blank lines it left behind). */
export function stripDigest(text: string): string {
  const start = text.indexOf(DIGEST_START);
  if (start === -1) return text;
  const end = text.indexOf(DIGEST_END, start);
  if (end === -1) return text;
  const after = text.slice(end + DIGEST_END.length).replace(/^(?:[ \t]*\r?\n)+/, '');
  return text.slice(0, start) + after;
}

/** Render the digest block; never exceeds MAX_DIGEST_LINES lines. */
export function renderDocDigest(spec: DocDigestSpec): string {
  const footer = spec.footer ?? DEFAULT_FOOTER;
  // start marker + header + blank quote + footer + end marker
  const room = Math.max(0, MAX_DIGEST_LINES - 5);
  const facts = spec.facts
    .filter((f) => f && f.trim().length > 0)
    .slice(0, room)
    .map((f) => `> - ${f.replace(/\s+/g, ' ').trim()}`);
  const lines = [
    DIGEST_START,
    `> **Digest** — ${spec.kind} (generated by ADO Code). Skim this first; full text below.`,
    ...facts,
    '>',
    `> ${footer}`,
    DIGEST_END,
  ];
  return lines.join('\n');
}

/** Strip any previous digest, then prepend `digest`. */
export function withDigest(body: string, digest: string): string {
  const clean = stripDigest(body).replace(/^(?:[ \t]*\r?\n)+/, '');
  return `${digest}\n\n${clean}`;
}

/** Line count of the digest block, or 0 when there is none. */
export function digestLineCount(text: string): number {
  const start = text.indexOf(DIGEST_START);
  if (start === -1) return 0;
  const end = text.indexOf(DIGEST_END, start);
  if (end === -1) return 0;
  return text.slice(start, end + DIGEST_END.length).split('\n').length;
}

/** True when the text opens with a digest block (after optional blank lines). */
export function hasDigest(text: string): boolean {
  return /^\s*<!-- ado-code:digest:start -->/.test(text);
}
