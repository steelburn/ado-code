/**
 * Per-family edge authentication — ZEN-STD-CON-05, the other three stacks.
 *
 * Why this module exists: `securityArtifacts.ts` covers the node stack, where the
 * gateway and the services share one TypeScript package. The python, .NET and
 * Laravel monorepos carry no `packages/shared`, so the clause stayed node-only and
 * was recorded as a residual. A residual is a weaker claim than a met clause, and
 * the three stacks do not actually need the TypeScript kit to refuse an
 * unauthenticated caller — they need the same twenty lines expressed in their own
 * standard library.
 *
 * The contract is identical to the node gateway's, byte for byte, because the
 * gateway stamps and the service verifies:
 *
 *   headers  x-auth-subject, x-auth-scopes, x-auth-issuer, x-auth-verified: edge,
 *            x-auth-stamp: <issuedAt>.<hex hmac-sha256>
 *   message  subject + "|" + scopes.join(" ") + "|" + issuer + "|" + issuedAt
 *   secret   EDGE_AUTH_SHARED_SECRET
 *   opt-out  EDGE_AUTH_REQUIRED=0 (unset means required — fail closed)
 *
 * Every implementation therefore uses hmac-sha256 over the same canonical string,
 * a constant-time comparison, and a freshness window, and every one of them
 * refuses rather than serves when the secret or the stamp is missing.
 */

import { OBSERVABILITY_PATHS } from './observabilityArtifacts';

/** Byte-identical to `IDENTITY_HEADERS` + `EDGE_STAMP_HEADER` in securityArtifacts. */
export const EDGE_GUARD_HEADERS = {
  subject: 'x-auth-subject',
  scopes: 'x-auth-scopes',
  issuer: 'x-auth-issuer',
  verified: 'x-auth-verified',
  stamp: 'x-auth-stamp',
} as const;

export const EDGE_GUARD_VERIFIED_VALUE = 'edge';
export const EDGE_GUARD_AUTH_ENV = 'EDGE_AUTH_REQUIRED';
export const EDGE_GUARD_SECRET_ENV = 'EDGE_AUTH_SHARED_SECRET';
export const EDGE_GUARD_MAX_AGE_SECONDS = 300;

/**
 * Paths a platform probe must reach before the caller is known. `/health` is in
 * the list because the container HEALTHCHECK probes it (see containerHardening).
 */
export const EDGE_GUARD_EXEMPT_PATHS: readonly string[] = [
  OBSERVABILITY_PATHS.legacy,
  OBSERVABILITY_PATHS.live,
  OBSERVABILITY_PATHS.ready,
  OBSERVABILITY_PATHS.metrics,
];

/** The error codes every family returns, so a client sees one vocabulary. */
export const EDGE_GUARD_ERROR_CODES = [
  'missing_identity',
  'unverified_identity',
  'missing_stamp',
  'bad_stamp',
  'stale_stamp',
  'missing_edge_secret',
] as const;

export const PYTHON_GUARD_PATH = 'app/security.py';
export const DOTNET_GUARD_PATH = 'Security/EdgeAuthMiddleware.cs';
export const PHP_GUARD_PATH = 'app/Http/Middleware/VerifyEdgeIdentity.php';

function pythonLiteralList(values: readonly string[]): string {
  return values.map((value) => `"${value}"`).join(', ');
}

/**
 * `app/security.py` — stdlib only (hmac/hashlib), plus the FastAPI middleware
 * wrapper. No PyJWT, no external dependency: a generated project must not gain a
 * package just to verify an HMAC it can compute itself.
 */
export function pythonEdgeGuard(serviceName: string): string {
  return [
    '"""Edge authentication — ZEN-STD-CON-05.',
    '',
    'The gateway validates the caller\'s JWT and forwards the identity it verified',
    'in x-auth-* headers, plus an HMAC stamp proving the edge produced them. This',
    'module re-verifies that stamp with the standard library, so a request that',
    'reaches the service without passing the gateway is refused instead of served.',
    '',
    'EDGE_AUTH_REQUIRED=0 is the only way past this, and it has to be deliberate:',
    'unset means required.',
    '"""',
    '',
    'from __future__ import annotations',
    '',
    'import hashlib',
    'import hmac',
    'import os',
    'import time',
    'from typing import Mapping',
    '',
    'from fastapi import Request',
    'from fastapi.responses import JSONResponse',
    '',
    `SUBJECT_HEADER = "${EDGE_GUARD_HEADERS.subject}"`,
    `SCOPES_HEADER = "${EDGE_GUARD_HEADERS.scopes}"`,
    `ISSUER_HEADER = "${EDGE_GUARD_HEADERS.issuer}"`,
    `VERIFIED_HEADER = "${EDGE_GUARD_HEADERS.verified}"`,
    `STAMP_HEADER = "${EDGE_GUARD_HEADERS.stamp}"`,
    `VERIFIED_VALUE = "${EDGE_GUARD_VERIFIED_VALUE}"`,
    '',
    `EDGE_AUTH_ENV = "${EDGE_GUARD_AUTH_ENV}"`,
    `SHARED_SECRET_ENV = "${EDGE_GUARD_SECRET_ENV}"`,
    `STAMP_MAX_AGE_SECONDS = ${EDGE_GUARD_MAX_AGE_SECONDS}`,
    '',
    '#: Platform probes answer before the caller is known.',
    `EXEMPT_PATHS = frozenset({${pythonLiteralList(EDGE_GUARD_EXEMPT_PATHS)}})`,
    '',
    '',
    'class EdgeAuthError(Exception):',
    '    """A request the edge did not authorise."""',
    '',
    '    def __init__(self, code: str, message: str) -> None:',
    '        super().__init__(message)',
    '        self.code = code',
    '        self.message = message',
    '',
    '',
    'def edge_required() -> bool:',
    '    value = os.environ.get(EDGE_AUTH_ENV, "1").strip().lower()',
    '    return value not in ("0", "false", "no")',
    '',
    '',
    'def _secret() -> str:',
    '    secret = os.environ.get(SHARED_SECRET_ENV, "")',
    '    if not secret:',
    '        raise EdgeAuthError(',
    '            "missing_edge_secret",',
    '            SHARED_SECRET_ENV + " is not set: the service cannot verify the edge stamp.",',
    '        )',
    '    return secret',
    '',
    '',
    'def canonical(subject: str, scopes: list[str], issuer: str, issued_at: int) -> str:',
    '    """The string the gateway signs. Must not change without the gateway."""',
    '    return "|".join([subject, " ".join(scopes), issuer, str(issued_at)])',
    '',
    '',
    'def sign(',
    '    subject: str,',
    '    scopes: list[str],',
    '    issuer: str,',
    '    issued_at: int,',
    '    secret: str,',
    ') -> str:',
    '    message = canonical(subject, scopes, issuer, issued_at).encode("utf-8")',
    '    return hmac.new(secret.encode("utf-8"), message, hashlib.sha256).hexdigest()',
    '',
    '',
    'def verify_stamp(',
    '    headers: Mapping[str, str],',
    '    now: int | None = None,',
    '    secret: str | None = None,',
    ') -> dict:',
    '    """Returns the principal or raises EdgeAuthError. Never returns None."""',
    '    subject = (headers.get(SUBJECT_HEADER) or "").strip()',
    '    if not subject:',
    '        raise EdgeAuthError("missing_identity", "The edge did not stamp an identity.")',
    '    if (headers.get(VERIFIED_HEADER) or "").strip() != VERIFIED_VALUE:',
    '        raise EdgeAuthError(',
    '            "unverified_identity",',
    '            "The request did not come through the gateway.",',
    '        )',
    '',
    '    stamp = (headers.get(STAMP_HEADER) or "").strip()',
    '    raw_at, _, presented = stamp.partition(".")',
    '    if not raw_at or not presented:',
    '        raise EdgeAuthError("missing_stamp", "The edge stamp is missing.")',
    '    try:',
    '        issued_at = int(raw_at)',
    '    except ValueError:',
    '        raise EdgeAuthError("bad_stamp", "The edge stamp is not a timestamp.") from None',
    '',
    '    clock = int(time.time()) if now is None else now',
    '    if abs(clock - issued_at) > STAMP_MAX_AGE_SECONDS:',
    '        raise EdgeAuthError(',
    '            "stale_stamp",',
    '            "The edge stamp is outside its freshness window.",',
    '        )',
    '',
    '    scopes = [scope for scope in (headers.get(SCOPES_HEADER) or "").split(" ") if scope]',
    '    issuer = (headers.get(ISSUER_HEADER) or "").strip() or "anonymous"',
    '    expected = sign(subject, scopes, issuer, issued_at, _secret() if secret is None else secret)',
    '    if not hmac.compare_digest(expected, presented.strip().lower()):',
    '        raise EdgeAuthError("bad_stamp", "The edge stamp does not verify.")',
    '',
    '    return {"subject": subject, "scopes": scopes, "issuer": issuer}',
    '',
    '',
    'async def edge_auth_middleware(request: Request, call_next):',
    '    """Registered in app/main.py; refuses before the route handler runs."""',
    '    if not edge_required() or request.url.path in EXEMPT_PATHS:',
    '        return await call_next(request)',
    '',
    '    try:',
    '        request.state.principal = verify_stamp(dict(request.headers))',
    '    except EdgeAuthError as error:',
    '        return JSONResponse(',
    '            status_code=401,',
    '            content={"error": error.code, "message": error.message},',
    '            headers={"WWW-Authenticate": \'Bearer realm="' + serviceName + '"\'},',
    '        )',
    '',
    '    return await call_next(request)',
    '',
  ].join('\n');
}

/**
 * `Security/EdgeAuthMiddleware.cs` — BCL only (`System.Security.Cryptography`).
 * A malformed stamp yields 401, never an exception: `Convert.FromHexString` throws
 * on odd length or a non-hex character, which would turn a forged header into a 500.
 */
export function dotnetEdgeGuard(namespaceBase: string, serviceName: string): string {
  return [
    'using System.Globalization;',
    'using System.Security.Cryptography;',
    'using System.Text;',
    '',
    `namespace ${namespaceBase}.Security;`,
    '',
    '/// <summary>',
    '/// Edge authentication — ZEN-STD-CON-05.',
    '///',
    '/// The gateway validates the caller\'s JWT and stamps the identity it verified',
    '/// into x-auth-* headers, signed with EDGE_AUTH_SHARED_SECRET. This middleware',
    '/// re-verifies that stamp so a request that bypasses the gateway is refused.',
    '/// EDGE_AUTH_REQUIRED=0 is the only opt-out; unset means required.',
    '/// </summary>',
    'public sealed class EdgeAuthMiddleware',
    '{',
    `    public const string SubjectHeader = "${EDGE_GUARD_HEADERS.subject}";`,
    `    public const string ScopesHeader = "${EDGE_GUARD_HEADERS.scopes}";`,
    `    public const string IssuerHeader = "${EDGE_GUARD_HEADERS.issuer}";`,
    `    public const string VerifiedHeader = "${EDGE_GUARD_HEADERS.verified}";`,
    `    public const string StampHeader = "${EDGE_GUARD_HEADERS.stamp}";`,
    `    public const string VerifiedValue = "${EDGE_GUARD_VERIFIED_VALUE}";`,
    `    public const string EdgeAuthEnv = "${EDGE_GUARD_AUTH_ENV}";`,
    `    public const string SharedSecretEnv = "${EDGE_GUARD_SECRET_ENV}";`,
    `    public const int StampMaxAgeSeconds = ${EDGE_GUARD_MAX_AGE_SECONDS};`,
    '',
    '    private static readonly string[] ExemptPaths = new[]',
    '    {',
    ...EDGE_GUARD_EXEMPT_PATHS.map((path) => `        "${path}",`),
    '    };',
    '',
    '    private static readonly string[] OptOutValues = new[] { "0", "false", "no" };',
    '',
    '    private readonly RequestDelegate _next;',
    '    private readonly ILogger<EdgeAuthMiddleware> _logger;',
    '',
    '    public EdgeAuthMiddleware(RequestDelegate next, ILogger<EdgeAuthMiddleware> logger)',
    '    {',
    '        _next = next;',
    '        _logger = logger;',
    '    }',
    '',
    '    public async Task InvokeAsync(HttpContext context)',
    '    {',
    '        if (!EdgeRequired() || IsExempt(context.Request.Path))',
    '        {',
    '            await _next(context);',
    '            return;',
    '        }',
    '',
    '        string? failure = Verify(context.Request.Headers, out Principal? principal);',
    '',
    '        if (failure is not null || principal is null)',
    '        {',
    '            _logger.LogWarning(',
    '                "Rejected an unauthenticated request to {Path}: {Reason}",',
    '                context.Request.Path.Value,',
    '                failure);',
    '',
    '            context.Response.StatusCode = StatusCodes.Status401Unauthorized;',
    `            context.Response.Headers.WwwAuthenticate = "Bearer realm=\\"${serviceName}\\"";`,
    '            await context.Response.WriteAsJsonAsync(new { error = failure });',
    '            return;',
    '        }',
    '',
    '        context.Items["principal"] = principal;',
    '        await _next(context);',
    '    }',
    '',
    '    /// <summary>Unset means required: a missing variable fails closed.</summary>',
    '    internal static bool EdgeRequired()',
    '    {',
    '        string value = (Environment.GetEnvironmentVariable(EdgeAuthEnv) ?? "1").Trim().ToLowerInvariant();',
    '        return !OptOutValues.Contains(value);',
    '    }',
    '',
    '    private static bool IsExempt(PathString path)',
    '        => Array.Exists(ExemptPaths, candidate => string.Equals(candidate, path.Value, StringComparison.Ordinal));',
    '',
    '    /// <summary>The canonical string the gateway signs; it must not drift.</summary>',
    '    internal static string Canonical(string subject, string scopes, string issuer, long issuedAt)',
    '        => string.Join("|", subject, scopes, issuer, issuedAt.ToString(CultureInfo.InvariantCulture));',
    '',
    '    internal static string Sign(string subject, string scopes, string issuer, long issuedAt, string secret)',
    '    {',
    '        using var hmac = new HMACSHA256(Encoding.UTF8.GetBytes(secret));',
    '        byte[] digest = hmac.ComputeHash(Encoding.UTF8.GetBytes(Canonical(subject, scopes, issuer, issuedAt)));',
    '        return Convert.ToHexString(digest).ToLowerInvariant();',
    '    }',
    '',
    '    /// <summary>Returns an error code, or null when the request is authorised.</summary>',
    '    internal static string? Verify(IHeaderDictionary headers, out Principal? principal)',
    '    {',
    '        principal = null;',
    '',
    '        string subject = (headers[SubjectHeader].ToString() ?? string.Empty).Trim();',
    '        if (subject.Length == 0)',
    '        {',
    '            return "missing_identity";',
    '        }',
    '',
    '        if (!string.Equals((headers[VerifiedHeader].ToString() ?? string.Empty).Trim(), VerifiedValue, StringComparison.Ordinal))',
    '        {',
    '            return "unverified_identity";',
    '        }',
    '',
    '        string stamp = (headers[StampHeader].ToString() ?? string.Empty).Trim();',
    '        int separator = stamp.IndexOf(\'.\', StringComparison.Ordinal);',
    '        if (separator <= 0 || separator == stamp.Length - 1)',
    '        {',
    '            return "missing_stamp";',
    '        }',
    '',
    '        if (!long.TryParse(stamp[..separator], NumberStyles.Integer, CultureInfo.InvariantCulture, out long issuedAt))',
    '        {',
    '            return "bad_stamp";',
    '        }',
    '',
    '        long now = DateTimeOffset.UtcNow.ToUnixTimeSeconds();',
    '        if (Math.Abs(now - issuedAt) > StampMaxAgeSeconds)',
    '        {',
    '            return "stale_stamp";',
    '        }',
    '',
    '        string secret = Environment.GetEnvironmentVariable(SharedSecretEnv) ?? string.Empty;',
    '        if (secret.Length == 0)',
    '        {',
    '            return "missing_edge_secret";',
    '        }',
    '',
    '        string scopes = (headers[ScopesHeader].ToString() ?? string.Empty).Trim();',
    '        string issuer = (headers[IssuerHeader].ToString() ?? string.Empty).Trim();',
    '        if (issuer.Length == 0)',
    '        {',
    '            issuer = "anonymous";',
    '        }',
    '',
    '        string presented = stamp[(separator + 1)..].Trim().ToLowerInvariant();',
    '        byte[] presentedBytes;',
    '        try',
    '        {',
    '            presentedBytes = Convert.FromHexString(presented);',
    '        }',
    '        catch (FormatException)',
    '        {',
    '            return "bad_stamp";',
    '        }',
    '',
    '        byte[] expected = Convert.FromHexString(Sign(subject, scopes, issuer, issuedAt, secret));',
    '        if (!CryptographicOperations.FixedTimeEquals(expected, presentedBytes))',
    '        {',
    '            return "bad_stamp";',
    '        }',
    '',
    '        principal = new Principal(',
    '            subject,',
    '            scopes.Split(\' \', StringSplitOptions.RemoveEmptyEntries),',
    '            issuer);',
    '',
    '        return null;',
    '    }',
    '}',
    '',
    '/// <summary>The caller the edge verified: subject, scopes, issuer.</summary>',
    'public sealed record Principal(string Subject, string[] Scopes, string Issuer);',
    '',
  ].join('\n');
}

/**
 * `app/Http/Middleware/VerifyEdgeIdentity.php` — `hash_hmac`/`hash_equals`, no
 * Composer package. Registered in bootstrap/app.php on the api group; the platform
 * paths are exempt inside the middleware so a probe never needs a token.
 */
export function phpEdgeGuard(serviceName: string): string {
  return [
    '<?php',
    '',
    'declare(strict_types=1);',
    '',
    'namespace App\\Http\\Middleware;',
    '',
    'use Closure;',
    'use Illuminate\\Http\\Request;',
    'use Symfony\\Component\\HttpFoundation\\Response;',
    '',
    '/**',
    ' * Edge authentication — ZEN-STD-CON-05.',
    ' *',
    ' * The gateway validates the caller\'s JWT and stamps the identity it verified',
    ' * into x-auth-* headers, signed with EDGE_AUTH_SHARED_SECRET. This middleware',
    ' * re-verifies that stamp so a request that bypasses the gateway is refused.',
    ' * EDGE_AUTH_REQUIRED=0 is the only opt-out; unset means required.',
    ' */',
    'final class VerifyEdgeIdentity',
    '{',
    `    private const SUBJECT_HEADER = '${EDGE_GUARD_HEADERS.subject}';`,
    `    private const SCOPES_HEADER = '${EDGE_GUARD_HEADERS.scopes}';`,
    `    private const ISSUER_HEADER = '${EDGE_GUARD_HEADERS.issuer}';`,
    `    private const VERIFIED_HEADER = '${EDGE_GUARD_HEADERS.verified}';`,
    `    private const STAMP_HEADER = '${EDGE_GUARD_HEADERS.stamp}';`,
    `    private const VERIFIED_VALUE = '${EDGE_GUARD_VERIFIED_VALUE}';`,
    `    private const EDGE_AUTH_ENV = '${EDGE_GUARD_AUTH_ENV}';`,
    `    private const SHARED_SECRET_ENV = '${EDGE_GUARD_SECRET_ENV}';`,
    `    private const STAMP_MAX_AGE_SECONDS = ${EDGE_GUARD_MAX_AGE_SECONDS};`,
    '',
    '    /** @var list<string> */',
    '    private const EXEMPT_PATHS = [',
    ...EDGE_GUARD_EXEMPT_PATHS.map((path) => `        '${path}',`),
    '    ];',
    '',
    '    public function handle(Request $request, Closure $next): Response',
    '    {',
    '        if (!self::edgeRequired() || in_array($this->path($request), self::EXEMPT_PATHS, true)) {',
    '            return $next($request);',
    '        }',
    '',
    '        $result = $this->verify($request);',
    '',
    '        if (is_string($result)) {',
    '            return new Response(',
    "                (string) json_encode(['error' => $result]),",
    '                401,',
    '                [',
    "                    'content-type' => 'application/json',",
    `                    'www-authenticate' => 'Bearer realm="${serviceName}"',`,
    '                ]',
    '            );',
    '        }',
    '',
    "        $request->attributes->set('principal', $result);",
    '',
    '        return $next($request);',
    '    }',
    '',
    '    private function path(Request $request): string',
    '    {',
    "        return '/' . ltrim($request->path(), '/');",
    '    }',
    '',
    '    private static function header(Request $request, string $name): string',
    '    {',
    '        $value = $request->headers->get($name);',
    '',
    '        return is_string($value) ? trim($value) : \'\';',
    '    }',
    '',
    '    /** Unset means required: a missing variable fails closed. */',
    '    public static function edgeRequired(): bool',
    '    {',
    "        $value = strtolower(trim((string) (getenv(self::EDGE_AUTH_ENV) ?: '1')));",
    '',
    "        return !in_array($value, ['0', 'false', 'no'], true);",
    '    }',
    '',
    '    /**',
    '     * Returns the error code, or the principal when the edge stamp verifies.',
    '     *',
    '     * @return array{subject: string, scopes: list<string>, issuer: string}|string',
    '     */',
    '    public function verify(Request $request): array|string',
    '    {',
    '        $subject = self::header($request, self::SUBJECT_HEADER);',
    "        if ($subject === '') {",
    "            return 'missing_identity';",
    '        }',
    '',
    '        if (self::header($request, self::VERIFIED_HEADER) !== self::VERIFIED_VALUE) {',
    "            return 'unverified_identity';",
    '        }',
    '',
    '        $stamp = self::header($request, self::STAMP_HEADER);',
    "        $separator = strpos($stamp, '.');",
    "        if ($separator === false || $separator === 0 || $separator === strlen($stamp) - 1) {",
    "            return 'missing_stamp';",
    '        }',
    '',
    '        $issuedAtRaw = substr($stamp, 0, $separator);',
    "        if ($issuedAtRaw === '' || !ctype_digit($issuedAtRaw)) {",
    "            return 'bad_stamp';",
    '        }',
    '        $issuedAt = (int) $issuedAtRaw;',
    '',
    '        if (abs(time() - $issuedAt) > self::STAMP_MAX_AGE_SECONDS) {',
    "            return 'stale_stamp';",
    '        }',
    '',
    "        $secret = (string) (getenv(self::SHARED_SECRET_ENV) ?: '');",
    "        if ($secret === '') {",
    "            return 'missing_edge_secret';",
    '        }',
    '',
    '        $scopesHeader = self::header($request, self::SCOPES_HEADER);',
    '        $issuer = self::header($request, self::ISSUER_HEADER);',
    "        if ($issuer === '') {",
    "            $issuer = 'anonymous';",
    '        }',
    '',
    '        $presented = strtolower(substr($stamp, $separator + 1));',
    "        $expected = hash_hmac('sha256', self::canonical($subject, $scopesHeader, $issuer, $issuedAt), $secret);",
    '',
    '        if (!hash_equals($expected, $presented)) {',
    "            return 'bad_stamp';",
    '        }',
    '',
    "        $scopes = array_values(array_filter(",
    "            explode(' ', $scopesHeader),",
    "            static fn (string $scope): bool => $scope !== ''",
    '        ));',
    '',
    "        return ['subject' => $subject, 'scopes' => $scopes, 'issuer' => $issuer];",
    '    }',
    '',
    '    /** The canonical string the gateway signs; it must not drift. */',
    '    public static function canonical(string $subject, string $scopes, string $issuer, int $issuedAt): string',
    '    {',
    "        return implode('|', [$subject, $scopes, $issuer, (string) $issuedAt]);",
    '    }',
    '',
    '    public static function sign(',
    '        string $subject,',
    '        string $scopes,',
    '        string $issuer,',
    '        int $issuedAt,',
    '        string $secret',
    '    ): string {',
    "        return hash_hmac('sha256', self::canonical($subject, $scopes, $issuer, $issuedAt), $secret);",
    '    }',
    '}',
    '',
  ].join('\n');
}

/** Files each family's tree receives, keyed by path inside the service folder. */
export function pythonEdgeGuardFiles(folder: string, serviceName: string): Record<string, string> {
  return { [`${folder}/${PYTHON_GUARD_PATH}`]: pythonEdgeGuard(serviceName) };
}

export function dotnetEdgeGuardFiles(
  folder: string,
  namespaceBase: string,
  serviceName: string
): Record<string, string> {
  return { [`${folder}/${DOTNET_GUARD_PATH}`]: dotnetEdgeGuard(namespaceBase, serviceName) };
}

export function phpEdgeGuardFiles(folder: string, serviceName: string): Record<string, string> {
  return { [`${folder}/${PHP_GUARD_PATH}`]: phpEdgeGuard(serviceName) };
}
